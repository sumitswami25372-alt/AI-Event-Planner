"""
PDF report generation service for CelebrAI.

Generates styled, multi-section PDF event plan documents using ReportLab.
All user-supplied text is XML-escaped before insertion to prevent injection
through the ReportLab XML/paragraph engine.
"""
from __future__ import annotations

import io
from typing import Any
from xml.sax import saxutils

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


def sanitize_text(text: Any) -> str:
    """Escapes user text for safe ReportLab XML generation."""
    if text is None:
        return ""
    s = str(text)
    return saxutils.escape(s)


def generate_event_pdf(event_data: dict[str, Any], expenses: list[dict[str, Any]], tasks: list[dict[str, Any]]) -> bytes:
    """
    Generates a production-quality, styled PDF report for a saved event.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    # Brand Palette
    c_primary = colors.HexColor("#4A154B")
    c_accent = colors.HexColor("#D4AF37")
    c_dark = colors.HexColor("#1F2937")
    c_light_bg = colors.HexColor("#F9FAFB")
    c_border = colors.HexColor("#E5E7EB")

    # Custom typography styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=28,
        textColor=c_primary,
        spaceAfter=4
    )

    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#6B7280"),
        spaceAfter=15
    )

    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=c_primary,
        spaceBefore=14,
        spaceAfter=8
    )

    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=c_dark
    )

    body_bold = ParagraphStyle(
        "BodyDarkBold",
        parent=body_style,
        fontName="Helvetica-Bold"
    )

    story = []

    # Title & Header
    event_name = sanitize_text(event_data.get("name", "Celebration"))
    category = sanitize_text(event_data.get("category", "Event")).capitalize()
    story.append(Paragraph(event_name, title_style))
    story.append(Paragraph(f"CelebrAI Master Event Plan &bull; {category} &bull; Generated by CelebrAI Intelligence", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=c_accent, spaceAfter=15))

    # Event Logistics Table
    currency = sanitize_text(event_data.get("currency", "INR"))
    budget = float(event_data.get("budget_amount", 0.0))
    guests = int(event_data.get("guest_count", 0))
    date = sanitize_text(event_data.get("event_date", "TBD"))
    location = sanitize_text(event_data.get("location", "TBD"))

    logistics_data = [
        [
            Paragraph("<b>Target Date:</b>", body_style), Paragraph(date, body_style),
            Paragraph("<b>Location:</b>", body_style), Paragraph(location, body_style)
        ],
        [
            Paragraph("<b>Guest Count:</b>", body_style), Paragraph(f"{guests} attendees", body_style),
            Paragraph("<b>Target Budget:</b>", body_style), Paragraph(f"{currency} {budget:,.2f}", body_style)
        ]
    ]

    logistics_table = Table(logistics_data, colWidths=[80, 180, 80, 190])
    logistics_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), c_light_bg),
        ('BOX', (0, 0), (-1, -1), 0.5, c_border),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, c_border),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(logistics_table)
    story.append(Spacer(1, 10))

    # AI Plan Details
    plan = event_data.get("plan_json") or {}
    if plan:
        # Concept & Theme
        story.append(Paragraph("1. Concept & Thematic Vision", section_heading))
        concept = sanitize_text(plan.get("event_concept", "Event overview"))
        theme = sanitize_text(plan.get("theme", "Signature Theme"))
        story.append(Paragraph(f"<b>Concept:</b> {concept}", body_style))
        story.append(Spacer(1, 4))
        story.append(Paragraph(f"<b>Theme:</b> {theme}", body_style))
        story.append(Spacer(1, 8))

        # Palette
        palette = plan.get("color_palette", [])
        if palette:
            p_text = " &bull; ".join([f"<font color='{saxutils.escape(c)}'>&#9632;</font> {saxutils.escape(c)}" for c in palette])
            story.append(Paragraph(f"<b>Palette:</b> {p_text}", body_style))
            story.append(Spacer(1, 8))

        # Venue Guidance & Decor
        decorations = plan.get("decorations", [])
        if decorations:
            story.append(Paragraph("Decor & Styling Guidelines:", body_bold))
            for d in decorations[:4]:
                story.append(Paragraph(f"&bull; {sanitize_text(d)}", body_style))
            story.append(Spacer(1, 6))

        # Timeline
        timeline = plan.get("timeline", [])
        if timeline:
            story.append(Paragraph("2. Event-Day Schedule & Run-of-Show", section_heading))
            timeline_table_data = [[
                Paragraph("<b>Time</b>", body_style),
                Paragraph("<b>Activity</b>", body_style),
                Paragraph("<b>Duration</b>", body_style)
            ]]
            for t in timeline:
                timeline_table_data.append([
                    Paragraph(sanitize_text(t.get("time")), body_style),
                    Paragraph(sanitize_text(t.get("activity")), body_style),
                    Paragraph(f"{t.get('duration_minutes', 30)} min", body_style)
                ])
            t_table = Table(timeline_table_data, colWidths=[90, 360, 80])
            t_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), c_light_bg),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('LINEBELOW', (0, 0), (-1, -1), 0.5, c_border),
            ]))
            story.append(t_table)
            story.append(Spacer(1, 10))

    # Expenses & Financial Ledger
    story.append(Paragraph("3. Budget Allocation & Expense Ledger", section_heading))
    if expenses:
        exp_table_data = [[
            Paragraph("<b>Expense / Item</b>", body_style),
            Paragraph("<b>Category</b>", body_style),
            Paragraph("<b>Estimated</b>", body_style),
            Paragraph("<b>Actual</b>", body_style)
        ]]
        total_est = 0.0
        total_act = 0.0
        for exp in expenses:
            e_amt = float(exp.get("estimated_amount", 0.0))
            a_amt = float(exp.get("actual_amount", 0.0))
            total_est += e_amt
            total_act += a_amt
            exp_table_data.append([
                Paragraph(sanitize_text(exp.get("name")), body_style),
                Paragraph(sanitize_text(exp.get("category")), body_style),
                Paragraph(f"{currency} {e_amt:,.2f}", body_style),
                Paragraph(f"{currency} {a_amt:,.2f}", body_style)
            ])
        exp_table_data.append([
            Paragraph("<b>TOTALS</b>", body_bold),
            Paragraph("", body_style),
            Paragraph(f"<b>{currency} {total_est:,.2f}</b>", body_bold),
            Paragraph(f"<b>{currency} {total_act:,.2f}</b>", body_bold)
        ])
        e_table = Table(exp_table_data, colWidths=[200, 130, 100, 100])
        e_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), c_light_bg),
            ('BACKGROUND', (0, -1), (-1, -1), c_light_bg),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('LINEBELOW', (0, 0), (-1, -1), 0.5, c_border),
        ]))
        story.append(e_table)
    else:
        story.append(Paragraph("No expense records logged yet.", body_style))
    story.append(Spacer(1, 10))

    # Checklist Tasks
    story.append(Paragraph("4. Preparation Checklist & Milestone Tracker", section_heading))
    if tasks:
        task_table_data = [[
            Paragraph("<b>Task</b>", body_style),
            Paragraph("<b>Category</b>", body_style),
            Paragraph("<b>Priority</b>", body_style),
            Paragraph("<b>Status</b>", body_style)
        ]]
        for task in tasks:
            is_done = task.get("completed", False)
            status_text = "<font color='#10B981'>COMPLETED</font>" if is_done else "<font color='#F59E0B'>PENDING</font>"
            task_table_data.append([
                Paragraph(sanitize_text(task.get("title")), body_style),
                Paragraph(sanitize_text(task.get("category", "General")), body_style),
                Paragraph(sanitize_text(task.get("priority", "medium")).upper(), body_style),
                Paragraph(status_text, body_style)
            ])
        task_table = Table(task_table_data, colWidths=[240, 110, 90, 90])
        task_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), c_light_bg),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('LINEBELOW', (0, 0), (-1, -1), 0.5, c_border),
        ]))
        story.append(task_table)
    else:
        story.append(Paragraph("No checklist tasks logged yet.", body_style))

    # Footer note
    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", thickness=0.5, color=c_border, spaceAfter=8))
    story.append(Paragraph(
        "<i>CelebrAI &bull; AI-Powered Planning & Orchestration &bull; Keep this document for vendor briefings and team alignment.</i>",
        subtitle_style
    ))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
